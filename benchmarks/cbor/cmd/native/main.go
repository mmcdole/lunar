// Command native runs the CBOR workload in provisioned native Lua interpreters.
// It never downloads or installs a runtime.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"math"
	"math/rand"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
	"time"
)

const (
	stagedDataPath        = "data/graph.cbor"
	nativeSchemaVersion   = 2
	nativeProtocolVersion = "native-reference-v1"
	minimumNativeRuns     = 15
)

type options struct {
	mode               string
	fixture            string
	data               string
	script             string
	lua51              string
	luajit             string
	expectLua51        string
	expectLuaJIT       string
	expectLua51SHA256  string
	expectLuaJITSHA256 string
	runs               int
	warmups            int
	seed               int64
	format             string
	includeLuaJITJIT   bool
	output             string
	overwrite          bool
	qualification      bool
}

type runtimeSpec struct {
	name            string
	binary          string
	executable      string
	arguments       []string
	expectedVersion string
	version         string
	binarySHA256    string
	expectSHA256    string
}

type result struct {
	RecordType      string `json:"record_type"`
	SchemaVersion   int    `json:"schema_version"`
	Runtime         string `json:"runtime"`
	RuntimeVersion  string `json:"runtime_version"`
	Binary          string `json:"binary"`
	BinarySHA256    string `json:"binary_sha256"`
	Mode            string `json:"mode"`
	Run             int    `json:"run"`
	Sequence        int    `json:"sequence"`
	Seed            int64  `json:"seed"`
	WallNS          int64  `json:"wall_ns"`
	UserCPUNS       int64  `json:"user_cpu_ns"`
	SystemCPUNS     int64  `json:"system_cpu_ns"`
	TotalCPUNS      int64  `json:"total_cpu_ns"`
	OperationCPUNS  int64  `json:"operation_cpu_ns"`
	LuaHeapBytes    uint64 `json:"lua_heap_bytes"`
	GraphDeltaBytes int64  `json:"graph_delta_bytes,omitempty"`
	InputSHA256     string `json:"input_sha256"`
	ScriptSHA256    string `json:"script_sha256"`
	CodecSHA256     string `json:"codec_sha256"`
	WorkloadSHA256  string `json:"workload_sha256"`
	GOOS            string `json:"goos"`
	GOARCH          string `json:"goarch"`
	LuaOutput       string `json:"lua_output,omitempty"`
	LuaStderr       string `json:"lua_stderr,omitempty"`
}

type runtimeIdentity struct {
	Runtime        string   `json:"runtime"`
	Version        string   `json:"version"`
	Binary         string   `json:"binary"`
	BinarySHA256   string   `json:"binary_sha256"`
	ExpectedSHA256 string   `json:"expected_sha256,omitempty"`
	Arguments      []string `json:"arguments,omitempty"`
}

type policyRecord struct {
	RecordType          string            `json:"record_type"`
	SchemaVersion       int               `json:"schema_version"`
	ProtocolVersion     string            `json:"protocol_version"`
	Qualification       bool              `json:"qualification"`
	ClockPolicy         string            `json:"clock_policy"`
	Mode                string            `json:"mode"`
	Runs                int               `json:"runs"`
	Warmups             int               `json:"warmups"`
	Seed                int64             `json:"seed"`
	LuaJITJITOnIncluded bool              `json:"luajit_jit_on_included"`
	CompletionRequired  bool              `json:"completion_required"`
	Runtimes            []runtimeIdentity `json:"runtimes"`
	InputSHA256         string            `json:"input_sha256"`
	ScriptSHA256        string            `json:"script_sha256"`
	CodecSHA256         string            `json:"codec_sha256"`
	WorkloadSHA256      string            `json:"workload_sha256"`
}

type completionRecord struct {
	RecordType      string         `json:"record_type"`
	SchemaVersion   int            `json:"schema_version"`
	ProtocolVersion string         `json:"protocol_version"`
	Qualification   bool           `json:"qualification"`
	Completed       bool           `json:"completed"`
	Mode            string         `json:"mode"`
	Samples         int            `json:"samples"`
	ExpectedSamples int            `json:"expected_samples"`
	RuntimeSamples  map[string]int `json:"runtime_samples"`
}

type luaMeasurement struct {
	OperationCPUNS  int64
	LuaHeapBytes    uint64
	GraphDeltaBytes int64
}

func main() {
	var opts options
	flag.StringVar(&opts.mode, "mode", "load", "operation to measure: load or save")
	flag.StringVar(&opts.fixture, "fixture", "testdata", "directory containing workload.lua and cbor.lua")
	flag.StringVar(&opts.data, "data", "", "CBOR input generated by cmd/generate (required)")
	flag.StringVar(&opts.script, "script", "", "optional Lua measurement script; defaults from -mode")
	flag.StringVar(&opts.lua51, "lua51", "", "path to a provisioned PUC Lua 5.1.5 binary")
	flag.StringVar(&opts.luajit, "luajit", "", "path to a provisioned LuaJIT 2.1 binary")
	flag.StringVar(&opts.expectLua51, "expect-lua51", "Lua 5.1.5", "required substring in the PUC Lua version output")
	flag.StringVar(&opts.expectLuaJIT, "expect-luajit", "LuaJIT 2.1", "required substring in the LuaJIT version output")
	flag.StringVar(&opts.expectLua51SHA256, "expect-lua51-sha256", "", "optional required SHA-256 for the PUC Lua 5.1.5 binary")
	flag.StringVar(&opts.expectLuaJITSHA256, "expect-luajit-sha256", "", "optional required SHA-256 for the LuaJIT 2.1 binary")
	flag.IntVar(&opts.runs, "runs", 15, "recorded fresh-process samples per runtime")
	flag.IntVar(&opts.warmups, "warmups", 2, "discarded fresh-process warmups per runtime")
	flag.Int64Var(&opts.seed, "seed", 1, "deterministic seed used to randomize runtime order")
	flag.StringVar(&opts.format, "format", "jsonl", "output format: jsonl or text")
	flag.BoolVar(&opts.includeLuaJITJIT, "luajit-jit", true, "also record the separately labelled LuaJIT JIT-on ceiling")
	flag.StringVar(&opts.output, "output", "", "new JSONL or text evidence path (default stdout)")
	flag.BoolVar(&opts.overwrite, "overwrite", false, "replace an existing evidence file")
	flag.BoolVar(&opts.qualification, "qualification", false, "require the complete pinned 15-run native-reference archive policy")
	flag.Parse()

	if err := execute(opts, os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "cbor-native:", err)
		os.Exit(1)
	}
}

func execute(opts options, output io.Writer) error {
	if err := validateOptions(&opts); err != nil {
		return err
	}
	specs, err := prepareRuntimeSpecs(opts)
	if err != nil {
		return err
	}
	stagingDirectory, err := stageRuntimeBinaries(specs)
	if err != nil {
		return err
	}
	defer os.RemoveAll(stagingDirectory)
	inputSHA256, err := hashFile(opts.data)
	if err != nil {
		return fmt.Errorf("hash input: %w", err)
	}
	scriptSHA256, err := hashFile(opts.script)
	if err != nil {
		return fmt.Errorf("hash script: %w", err)
	}
	codecSHA256, err := hashFile(filepath.Join(opts.fixture, "cbor.lua"))
	if err != nil {
		return fmt.Errorf("hash codec: %w", err)
	}
	workloadSHA256, err := hashFile(filepath.Join(opts.fixture, "workload.lua"))
	if err != nil {
		return fmt.Errorf("hash workload: %w", err)
	}
	executionOpts := opts
	executionOpts.fixture = filepath.Join(stagingDirectory, "fixture")
	executionOpts.data = filepath.Join(stagingDirectory, "graph.cbor")
	executionOpts.script = filepath.Join(stagingDirectory, "measurement.lua")
	for _, asset := range []struct {
		name     string
		source   string
		target   string
		expected string
	}{
		{name: "input", source: opts.data, target: executionOpts.data, expected: inputSHA256},
		{name: "script", source: opts.script, target: executionOpts.script, expected: scriptSHA256},
		{name: "codec", source: filepath.Join(opts.fixture, "cbor.lua"), target: filepath.Join(executionOpts.fixture, "cbor.lua"), expected: codecSHA256},
		{name: "workload", source: filepath.Join(opts.fixture, "workload.lua"), target: filepath.Join(executionOpts.fixture, "workload.lua"), expected: workloadSHA256},
	} {
		if err := copyReadOnlyVerified(asset.source, asset.target, asset.expected); err != nil {
			return fmt.Errorf("stage %s: %w", asset.name, err)
		}
	}

	destination := output
	var outputFile *os.File
	if opts.output != "" {
		outputFile, err = createEvidenceFile(opts.output, opts.overwrite)
		if err != nil {
			return fmt.Errorf("open evidence: %w", err)
		}
		defer outputFile.Close()
		destination = outputFile
	}
	policy := buildPolicyRecord(opts, specs, inputSHA256, scriptSHA256, codecSHA256, workloadSHA256)
	if err := emitPolicy(destination, opts.format, policy); err != nil {
		return err
	}

	random := rand.New(rand.NewSource(opts.seed))
	sequence := 0
	runtimeSamples := make(map[string]int, len(specs))
	for round := -opts.warmups; round < opts.runs; round++ {
		ordered := append([]runtimeSpec(nil), specs...)
		random.Shuffle(len(ordered), func(left, right int) {
			ordered[left], ordered[right] = ordered[right], ordered[left]
		})
		for _, spec := range ordered {
			measured, err := runOne(executionOpts, spec, inputSHA256, scriptSHA256, codecSHA256, workloadSHA256)
			if err != nil {
				phase := fmt.Sprintf("run %d", round+1)
				if round < 0 {
					phase = fmt.Sprintf("warmup %d", round+opts.warmups+1)
				}
				return fmt.Errorf("%s for %s: %w", phase, spec.name, err)
			}
			if round < 0 {
				continue
			}
			sequence++
			measured.Run = round + 1
			measured.Sequence = sequence
			if err := emit(destination, opts.format, measured); err != nil {
				return err
			}
			runtimeSamples[spec.name]++
		}
	}
	expectedSamples := opts.runs * len(specs)
	completed := sequence == expectedSamples
	for _, spec := range specs {
		completed = completed && runtimeSamples[spec.name] == opts.runs
	}
	completion := completionRecord{
		RecordType: "completion", SchemaVersion: nativeSchemaVersion, ProtocolVersion: nativeProtocolVersion,
		Qualification: opts.qualification, Completed: completed, Mode: opts.mode,
		Samples: sequence, ExpectedSamples: expectedSamples, RuntimeSamples: runtimeSamples,
	}
	if err := emitCompletion(destination, opts.format, completion); err != nil {
		return err
	}
	if !completed {
		return fmt.Errorf("native archive incomplete: wrote %d of %d samples", sequence, expectedSamples)
	}
	if outputFile != nil {
		if err := outputFile.Sync(); err != nil {
			return fmt.Errorf("sync evidence: %w", err)
		}
	}
	return nil
}

func validateOptions(opts *options) error {
	if opts.mode != "load" && opts.mode != "save" {
		return fmt.Errorf("invalid -mode %q: expected load or save", opts.mode)
	}
	if opts.lua51 == "" && opts.luajit == "" {
		return fmt.Errorf("provide -lua51 and/or -luajit; runtimes are never downloaded automatically")
	}
	if opts.data == "" {
		return fmt.Errorf("-data is required; generate a corpus with cmd/generate")
	}
	if opts.runs < 1 {
		return fmt.Errorf("-runs must be at least 1")
	}
	if opts.warmups < 0 {
		return fmt.Errorf("-warmups cannot be negative")
	}
	if opts.format != "jsonl" && opts.format != "text" {
		return fmt.Errorf("invalid -format %q: expected jsonl or text", opts.format)
	}
	for name, expected := range map[string]*string{
		"-expect-lua51-sha256":  &opts.expectLua51SHA256,
		"-expect-luajit-sha256": &opts.expectLuaJITSHA256,
	} {
		if err := normalizeExpectedSHA256(name, expected); err != nil {
			return err
		}
	}
	if opts.qualification {
		if opts.lua51 == "" || opts.luajit == "" {
			return errors.New("-qualification requires both -lua51 and -luajit")
		}
		if opts.expectLua51SHA256 == "" || opts.expectLuaJITSHA256 == "" {
			return errors.New("-qualification requires -expect-lua51-sha256 and -expect-luajit-sha256")
		}
		if opts.runs < minimumNativeRuns {
			return fmt.Errorf("-qualification requires at least %d recorded runs per runtime", minimumNativeRuns)
		}
		if opts.format != "jsonl" {
			return errors.New("-qualification requires -format jsonl")
		}
		if opts.output == "" {
			return errors.New("-qualification requires an explicit -output evidence path")
		}
		if !opts.includeLuaJITJIT {
			return errors.New("-qualification requires both LuaJIT JIT-off and JIT-on records; remove -luajit-jit=false")
		}
	}
	if opts.script == "" {
		name := "load.lua"
		if opts.mode == "save" {
			name = "save.lua"
		}
		opts.script = filepath.Join("scripts", name)
	}

	for label, path := range map[string]string{
		"fixture": opts.fixture,
		"data":    opts.data,
		"script":  opts.script,
	} {
		absolute, err := filepath.Abs(path)
		if err != nil {
			return fmt.Errorf("resolve %s: %w", label, err)
		}
		switch label {
		case "fixture":
			opts.fixture = absolute
		case "data":
			opts.data = absolute
		case "script":
			opts.script = absolute
		}
	}
	for _, path := range []string{
		filepath.Join(opts.fixture, "workload.lua"),
		filepath.Join(opts.fixture, "cbor.lua"),
		opts.data,
		opts.script,
	} {
		if info, err := os.Stat(path); err != nil {
			return fmt.Errorf("required file %s: %w", path, err)
		} else if info.IsDir() {
			return fmt.Errorf("required file %s is a directory", path)
		}
	}
	if opts.output != "" {
		absolute, err := filepath.Abs(opts.output)
		if err != nil {
			return fmt.Errorf("resolve output: %w", err)
		}
		opts.output = absolute
		if !opts.overwrite {
			if _, err := os.Stat(absolute); err == nil {
				return fmt.Errorf("output %s already exists; choose a new path or pass -overwrite", absolute)
			} else if !os.IsNotExist(err) {
				return fmt.Errorf("inspect output %s: %w", absolute, err)
			}
		}
	}
	return nil
}

func normalizeExpectedSHA256(flagName string, expected *string) error {
	if *expected == "" {
		return nil
	}
	*expected = strings.ToLower(*expected)
	if len(*expected) != sha256.Size*2 {
		return fmt.Errorf("%s must contain 64 hexadecimal characters", flagName)
	}
	if _, err := hex.DecodeString(*expected); err != nil {
		return fmt.Errorf("invalid %s: %w", flagName, err)
	}
	return nil
}

func prepareRuntimeSpecs(opts options) ([]runtimeSpec, error) {
	var specs []runtimeSpec
	if opts.lua51 != "" {
		specs = append(specs, runtimeSpec{
			name: "puc-lua-5.1", binary: opts.lua51, expectedVersion: opts.expectLua51, expectSHA256: opts.expectLua51SHA256,
		})
	}
	if opts.luajit != "" {
		specs = append(specs, runtimeSpec{
			name: "luajit-2.1-jit-off", binary: opts.luajit, arguments: []string{"-joff"}, expectedVersion: opts.expectLuaJIT, expectSHA256: opts.expectLuaJITSHA256,
		})
		if opts.includeLuaJITJIT {
			specs = append(specs, runtimeSpec{
				name: "luajit-2.1-jit-on", binary: opts.luajit, expectedVersion: opts.expectLuaJIT, expectSHA256: opts.expectLuaJITSHA256,
			})
		}
	}
	for index := range specs {
		resolved, err := exec.LookPath(specs[index].binary)
		if err != nil {
			return nil, fmt.Errorf("find %s binary %q: %w", specs[index].name, specs[index].binary, err)
		}
		absolute, err := filepath.Abs(resolved)
		if err != nil {
			return nil, fmt.Errorf("resolve %s binary: %w", specs[index].name, err)
		}
		specs[index].binary = absolute
		specs[index].binarySHA256, err = hashFile(absolute)
		if err != nil {
			return nil, fmt.Errorf("hash %s binary: %w", specs[index].name, err)
		}
		if specs[index].expectSHA256 != "" && specs[index].binarySHA256 != specs[index].expectSHA256 {
			return nil, fmt.Errorf("%s SHA-256 %s does not match required %s", specs[index].name, specs[index].binarySHA256, specs[index].expectSHA256)
		}
	}
	return specs, nil
}

func buildPolicyRecord(opts options, specs []runtimeSpec, inputSHA256, scriptSHA256, codecSHA256, workloadSHA256 string) policyRecord {
	identities := make([]runtimeIdentity, 0, len(specs))
	for _, spec := range specs {
		identities = append(identities, runtimeIdentity{
			Runtime: spec.name, Version: spec.version, Binary: spec.binary,
			BinarySHA256: spec.binarySHA256, ExpectedSHA256: spec.expectSHA256,
			Arguments: append([]string(nil), spec.arguments...),
		})
	}
	return policyRecord{
		RecordType: "policy", SchemaVersion: nativeSchemaVersion, ProtocolVersion: nativeProtocolVersion,
		Qualification: opts.qualification,
		ClockPolicy:   "native fields are descriptive outside comparisons with identical clock semantics",
		Mode:          opts.mode, Runs: opts.runs, Warmups: opts.warmups, Seed: opts.seed,
		LuaJITJITOnIncluded: opts.includeLuaJITJIT, CompletionRequired: true,
		Runtimes: identities, InputSHA256: inputSHA256, ScriptSHA256: scriptSHA256,
		CodecSHA256: codecSHA256, WorkloadSHA256: workloadSHA256,
	}
}

func stageRuntimeBinaries(specs []runtimeSpec) (string, error) {
	directory, err := os.MkdirTemp("", "lunar-cbor-native-runtimes-")
	if err != nil {
		return "", fmt.Errorf("create private runtime staging directory: %w", err)
	}
	fail := func(err error) (string, error) {
		os.RemoveAll(directory)
		return "", err
	}
	type stagedRuntime struct {
		path   string
		digest string
	}
	stagedBySource := make(map[string]stagedRuntime, len(specs))
	for index := range specs {
		staged, found := stagedBySource[specs[index].binary]
		if !found {
			staged.path = filepath.Join(directory, fmt.Sprintf("%02d-%s", len(stagedBySource), filepath.Base(specs[index].binary)))
			if err := copyExecutable(specs[index].binary, staged.path); err != nil {
				return fail(fmt.Errorf("stage %s binary: %w", specs[index].name, err))
			}
			staged.digest, err = hashFile(staged.path)
			if err != nil {
				return fail(fmt.Errorf("hash staged %s binary: %w", specs[index].name, err))
			}
			stagedBySource[specs[index].binary] = staged
		}
		if staged.digest != specs[index].binarySHA256 {
			return fail(fmt.Errorf("%s binary changed while it was staged: prepared SHA-256 %s, staged SHA-256 %s", specs[index].name, specs[index].binarySHA256, staged.digest))
		}
		specs[index].executable = staged.path
		versionOutput, err := exec.Command(staged.path, "-v").CombinedOutput()
		if err != nil {
			return fail(fmt.Errorf("query staged %s version: %w: %s", specs[index].name, err, bytes.TrimSpace(versionOutput)))
		}
		specs[index].version = strings.Join(strings.Fields(string(versionOutput)), " ")
		if !strings.Contains(specs[index].version, specs[index].expectedVersion) {
			return fail(fmt.Errorf("%s version %q does not contain required %q", specs[index].name, specs[index].version, specs[index].expectedVersion))
		}
	}
	return directory, nil
}

func runOne(opts options, spec runtimeSpec, inputSHA256, scriptSHA256, codecSHA256, workloadSHA256 string) (result, error) {
	workdir, err := os.MkdirTemp("", "lunar-cbor-native-")
	if err != nil {
		return result{}, err
	}
	defer os.RemoveAll(workdir)
	for _, source := range []struct {
		from string
		to   string
	}{
		{from: filepath.Join(opts.fixture, "workload.lua"), to: filepath.Join(workdir, "workload.lua")},
		{from: filepath.Join(opts.fixture, "cbor.lua"), to: filepath.Join(workdir, "cbor.lua")},
		{from: opts.data, to: filepath.Join(workdir, filepath.FromSlash(stagedDataPath))},
	} {
		if err := copyFile(source.from, source.to); err != nil {
			return result{}, err
		}
	}

	arguments := append(append([]string(nil), spec.arguments...), opts.script)
	command := exec.Command(spec.executable, arguments...)
	command.Env = append(os.Environ(), "LUNAR_CBOR_FIXTURE="+workdir)
	var stdout, stderr bytes.Buffer
	command.Stdout = &stdout
	command.Stderr = &stderr
	started := time.Now()
	err = command.Run()
	wall := time.Since(started)
	if err != nil {
		return result{}, fmt.Errorf("native process: %w; stdout=%q stderr=%q", err, stdout.String(), stderr.String())
	}
	if command.ProcessState == nil {
		return result{}, fmt.Errorf("native process returned no process state")
	}
	userCPU := command.ProcessState.UserTime()
	systemCPU := command.ProcessState.SystemTime()
	luaMetrics, err := parseLuaMeasurement(stdout.String())
	if err != nil {
		return result{}, fmt.Errorf("parse native measurement: %w; stdout=%q", err, stdout.String())
	}
	return result{
		RecordType: "sample", SchemaVersion: nativeSchemaVersion,
		Runtime: spec.name, RuntimeVersion: spec.version,
		Binary: spec.binary, BinarySHA256: spec.binarySHA256,
		Mode: opts.mode, Seed: opts.seed,
		WallNS: wall.Nanoseconds(), UserCPUNS: userCPU.Nanoseconds(), SystemCPUNS: systemCPU.Nanoseconds(),
		TotalCPUNS:      userCPU.Nanoseconds() + systemCPU.Nanoseconds(),
		OperationCPUNS:  luaMetrics.OperationCPUNS,
		LuaHeapBytes:    luaMetrics.LuaHeapBytes,
		GraphDeltaBytes: luaMetrics.GraphDeltaBytes,
		InputSHA256:     inputSHA256, ScriptSHA256: scriptSHA256,
		CodecSHA256: codecSHA256, WorkloadSHA256: workloadSHA256,
		GOOS: runtime.GOOS, GOARCH: runtime.GOARCH,
		LuaOutput: strings.TrimSpace(stdout.String()), LuaStderr: strings.TrimSpace(stderr.String()),
	}, nil
}

func parseLuaMeasurement(output string) (luaMeasurement, error) {
	var measured luaMeasurement
	for _, field := range strings.Fields(output) {
		name, raw, found := strings.Cut(field, "=")
		if !found {
			continue
		}
		value, err := strconv.ParseFloat(raw, 64)
		if err != nil {
			return luaMeasurement{}, fmt.Errorf("invalid %s value %q: %w", name, raw, err)
		}
		switch name {
		case "cpu_seconds":
			measured.OperationCPUNS = int64(math.Round(value * float64(time.Second)))
		case "heap_kib":
			measured.LuaHeapBytes = uint64(math.Round(value * 1024))
		case "graph_delta_kib":
			measured.GraphDeltaBytes = int64(math.Round(value * 1024))
		}
	}
	if measured.OperationCPUNS <= 0 {
		return luaMeasurement{}, errors.New("missing positive cpu_seconds field")
	}
	if measured.LuaHeapBytes == 0 {
		return luaMeasurement{}, errors.New("missing positive heap_kib field")
	}
	return measured, nil
}

func emit(output io.Writer, format string, measured result) error {
	switch format {
	case "jsonl":
		return json.NewEncoder(output).Encode(measured)
	case "text":
		_, err := fmt.Fprintf(output,
			"runtime=%s mode=%s run=%d sequence=%d wall=%s user_cpu=%s system_cpu=%s operation_cpu=%s lua_heap_bytes=%d graph_delta_bytes=%d input_sha256=%s lua_output=%q\n",
			measured.Runtime, measured.Mode, measured.Run, measured.Sequence,
			time.Duration(measured.WallNS), time.Duration(measured.UserCPUNS), time.Duration(measured.SystemCPUNS),
			time.Duration(measured.OperationCPUNS), measured.LuaHeapBytes, measured.GraphDeltaBytes,
			measured.InputSHA256, measured.LuaOutput)
		return err
	default:
		return fmt.Errorf("unsupported output format %q", format)
	}
}

func emitPolicy(output io.Writer, format string, policy policyRecord) error {
	if format == "jsonl" {
		return json.NewEncoder(output).Encode(policy)
	}
	_, err := fmt.Fprintf(output,
		"policy=%s qualification=%t mode=%s runs=%d warmups=%d completion_required=%t clock_policy=%q\n",
		policy.ProtocolVersion, policy.Qualification, policy.Mode, policy.Runs, policy.Warmups,
		policy.CompletionRequired, policy.ClockPolicy,
	)
	return err
}

func emitCompletion(output io.Writer, format string, completion completionRecord) error {
	if format == "jsonl" {
		return json.NewEncoder(output).Encode(completion)
	}
	_, err := fmt.Fprintf(output,
		"completion=%s qualification=%t completed=%t mode=%s samples=%d expected_samples=%d\n",
		completion.ProtocolVersion, completion.Qualification, completion.Completed,
		completion.Mode, completion.Samples, completion.ExpectedSamples,
	)
	return err
}

func copyFile(source, destination string) error {
	if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
		return fmt.Errorf("create destination for %s: %w", destination, err)
	}
	input, err := os.Open(source)
	if err != nil {
		return fmt.Errorf("open %s: %w", source, err)
	}
	defer input.Close()
	output, err := os.Create(destination)
	if err != nil {
		return fmt.Errorf("create %s: %w", destination, err)
	}
	if _, err := io.Copy(output, input); err != nil {
		output.Close()
		return fmt.Errorf("copy %s: %w", source, err)
	}
	if err := output.Close(); err != nil {
		return fmt.Errorf("close %s: %w", destination, err)
	}
	return nil
}

func copyExecutable(source, destination string) error {
	input, err := os.Open(source)
	if err != nil {
		return err
	}
	defer input.Close()
	output, err := os.OpenFile(destination, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o500)
	if err != nil {
		return err
	}
	closed := false
	defer func() {
		if !closed {
			output.Close()
		}
	}()
	if _, err := io.Copy(output, input); err != nil {
		return err
	}
	if err := output.Sync(); err != nil {
		return err
	}
	if err := output.Close(); err != nil {
		return err
	}
	closed = true
	return os.Chmod(destination, 0o500)
}

func copyReadOnlyVerified(source, destination, expectedSHA256 string) error {
	if err := os.MkdirAll(filepath.Dir(destination), 0o700); err != nil {
		return err
	}
	input, err := os.Open(source)
	if err != nil {
		return err
	}
	defer input.Close()
	output, err := os.OpenFile(destination, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o400)
	if err != nil {
		return err
	}
	closed := false
	defer func() {
		if !closed {
			output.Close()
		}
	}()
	if _, err := io.Copy(output, input); err != nil {
		return err
	}
	if err := output.Sync(); err != nil {
		return err
	}
	if err := output.Close(); err != nil {
		return err
	}
	closed = true
	if err := os.Chmod(destination, 0o400); err != nil {
		return err
	}
	digest, err := hashFile(destination)
	if err != nil {
		return err
	}
	if digest != expectedSHA256 {
		return fmt.Errorf("source changed while it was staged: prepared SHA-256 %s, staged SHA-256 %s", expectedSHA256, digest)
	}
	return nil
}

func createEvidenceFile(path string, overwrite bool) (*os.File, error) {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return nil, err
	}
	flags := os.O_CREATE | os.O_WRONLY
	if overwrite {
		flags |= os.O_TRUNC
	} else {
		flags |= os.O_EXCL
	}
	return os.OpenFile(path, flags, 0o644)
}

func hashFile(path string) (string, error) {
	file, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer file.Close()
	hash := sha256.New()
	if _, err := io.Copy(hash, file); err != nil {
		return "", err
	}
	return hex.EncodeToString(hash.Sum(nil)), nil
}
